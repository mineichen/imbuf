//! Requires a browser, e.g. `wasm-pack test --headless --firefox imbuf-websys`
#![cfg(target_arch = "wasm32")]

use wasm_bindgen_test::{wasm_bindgen_test, wasm_bindgen_test_configure};

wasm_bindgen_test_configure!(run_in_browser);

/// 2x1 RGBA PNG with the pixels `[1, 2, 3, 255]` and `[4, 5, 6, 128]`
const PNG: &[u8] = &[
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
    0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0xf4, 0x22, 0x7f,
    0x8a, 0x00, 0x00, 0x00, 0x14, 0x49, 0x44, 0x41, 0x54, 0x78, 0x01, 0x01, 0x09, 0x00, 0xf6, 0xff,
    0x00, 0x01, 0x02, 0x03, 0xff, 0x04, 0x05, 0x06, 0x80, 0x05, 0xd7, 0x01, 0x95, 0x0b, 0x95, 0x51,
    0x6d, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
];

#[wasm_bindgen_test]
async fn load_png_rgba8() {
    let image = imbuf_websys::load_from_memory(PNG).await.unwrap();
    assert_eq!(image.dimensions().0.get(), 2);
    assert_eq!(image.dimensions().1.get(), 1);
    // The alpha of the second pixel can lose precision, if a browser premultiplies internally
    let [first, second] = image.buffer() else {
        panic!("Expected 2 pixels");
    };
    assert_eq!(first, &[1, 2, 3, 255]);
    assert_eq!(second[3], 128);
}

#[wasm_bindgen_test]
async fn load_garbage_fails() {
    assert!(imbuf_websys::load_from_memory(&[1, 2, 3]).await.is_err());
}
